const express = require('express');
const asyncHandler = require('../../../../middlewares/asyncHandler');
const authPublic = require('../../../auth/public');
const controller = require('../controllers/extensionCommand.controller');
const router = express.Router();
const write = authPublic.authorizeAnyPermission('ORDERS:WRITE', 'FINANCE:WRITE');
const read = authPublic.authorizeAnyPermission('ORDERS:READ', 'ORDERS:WRITE', 'FINANCE:READ', 'FINANCE:WRITE');
const managementRead = authPublic.authorizeAnyPermission('ORDERS:READ', 'ORDERS:WRITE', 'FINANCE:READ', 'FINANCE:WRITE', 'CATALOG:READ', 'CATALOG:WRITE');
const financeRead = authPublic.authorizeAnyPermission('FINANCE:READ', 'FINANCE:WRITE');
const financeWrite = authPublic.authorizeAnyPermission('FINANCE:WRITE');
router.get('/agents', authPublic.authenticate, read, asyncHandler(controller.listAgents));
router.get('/management-agents', authPublic.authenticate, managementRead, asyncHandler(controller.listManagementAgents));
router.get('/commands', authPublic.authenticate, read, asyncHandler(controller.listCommands));
router.post('/commands', authPublic.authenticate, write, asyncHandler(controller.createCommand));
router.get('/order-schedules', authPublic.authenticate, read, asyncHandler(controller.listOrderSchedules));
router.put('/order-schedules/:agentId', authPublic.authenticate, write, asyncHandler(controller.upsertOrderSchedule));
router.get('/finance-schedules', authPublic.authenticate, financeRead, asyncHandler(controller.listFinanceSchedules));
router.put('/finance-schedules/:agentId/:source', authPublic.authenticate, financeWrite, asyncHandler(controller.upsertFinanceSchedule));
router.post('/finance-schedules/:agentId/:source/request-now', authPublic.authenticate, financeWrite, asyncHandler(controller.requestFinanceScheduleNow));
router.post('/agent/heartbeat', authPublic.authenticate, write, asyncHandler(controller.heartbeat));
router.get('/agent/commands', authPublic.authenticate, read, asyncHandler(controller.listCurrentCommands));
router.post('/agent/import-new-orders', authPublic.authenticate, write, asyncHandler(controller.queueCurrentOrderImport));
router.post('/agent/import-ads-spend', authPublic.authenticate, financeWrite, asyncHandler(controller.queueCurrentAdsImport));
router.post('/agent/claim', authPublic.authenticate, write, asyncHandler(controller.claimNext));
router.post('/agent/commands/:commandId/start', authPublic.authenticate, write, asyncHandler(controller.startCommand));
router.post('/agent/commands/:commandId/renew', authPublic.authenticate, write, asyncHandler(controller.renewCommand));
router.post('/agent/commands/:commandId/complete', authPublic.authenticate, write, asyncHandler(controller.completeCommand));
module.exports = router;
